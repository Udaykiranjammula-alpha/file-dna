package com.filedna.app.core;

import android.graphics.Bitmap;
import android.graphics.Canvas;
import android.graphics.Color;
import android.graphics.Paint;
import android.graphics.pdf.PdfDocument;
import java.io.File;
import java.io.FileOutputStream;
import java.util.List;

public class PdfTools {

    public static boolean createPdfFromText(File outputFile, String text, String title) {
        PdfDocument document = new PdfDocument();
        try {
            int pageWidth = 595; // A4 standard point width
            int pageHeight = 842; // A4 standard point height
            int margin = 50;
            int y = margin;
            int pageNumber = 1;

            PdfDocument.PageInfo pageInfo = new PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create();
            PdfDocument.Page page = document.startPage(pageInfo);
            Canvas canvas = page.getCanvas();

            Paint titlePaint = new Paint();
            titlePaint.setColor(Color.BLACK);
            titlePaint.setTextSize(16);
            titlePaint.setFakeBoldText(true);

            Paint textPaint = new Paint();
            textPaint.setColor(Color.DKGRAY);
            textPaint.setTextSize(12);

            Paint footerPaint = new Paint();
            footerPaint.setColor(Color.GRAY);
            footerPaint.setTextSize(9);

            // Draw header
            canvas.drawText(title != null && !title.isEmpty() ? title : "FileDNA Document", margin, y, titlePaint);
            y += 28;

            canvas.drawLine(margin, y, pageWidth - margin, y, footerPaint);
            y += 24;

            String[] lines = text.split("\n");
            for (String line : lines) {
                if (y > pageHeight - margin - 20) {
                    // Footer
                    canvas.drawText("Page " + pageNumber + " • Generated by FileDNA Mobile", margin, pageHeight - 30, footerPaint);
                    document.finishPage(page);

                    pageNumber++;
                    pageInfo = new PdfDocument.PageInfo.Builder(pageWidth, pageHeight, pageNumber).create();
                    page = document.startPage(pageInfo);
                    canvas = page.getCanvas();
                    y = margin;
                }

                canvas.drawText(line, margin, y, textPaint);
                y += 18;
            }

            // Final footer
            canvas.drawText("Page " + pageNumber + " • Generated by FileDNA Mobile", margin, pageHeight - 30, footerPaint);
            document.finishPage(page);

            FileOutputStream fos = new FileOutputStream(outputFile);
            document.writeTo(fos);
            fos.close();
            return true;
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        } finally {
            document.close();
        }
    }

    public static boolean createPdfFromBitmaps(File outputFile, List<Bitmap> bitmaps) {
        if (bitmaps == null || bitmaps.isEmpty()) return false;
        PdfDocument document = new PdfDocument();
        try {
            int pageNumber = 1;
            for (Bitmap bmp : bitmaps) {
                PdfDocument.PageInfo pageInfo = new PdfDocument.PageInfo.Builder(bmp.getWidth(), bmp.getHeight(), pageNumber++).create();
                PdfDocument.Page page = document.startPage(pageInfo);
                Canvas canvas = page.getCanvas();
                canvas.drawBitmap(bmp, 0, 0, null);
                document.finishPage(page);
            }

            FileOutputStream fos = new FileOutputStream(outputFile);
            document.writeTo(fos);
            fos.close();
            return true;
        } catch (Exception e) {
            e.printStackTrace();
            return false;
        } finally {
            document.close();
        }
    }
}
